# Number of worker threads of the compiled engine: bpnworkers(BPPARAM) when BPPARAM is given (the
# engine never forks; BPPARAM only says how many cores to use), otherwise nThreads.
.stc_threads <- function(nThreads = 1L, BPPARAM = NULL) {
  n <- if (!is.null(BPPARAM)) BiocParallel::bpnworkers(BPPARAM) else nThreads
  if (!is.numeric(n) || length(n) != 1L || is.na(n) || n < 1 || n != round(n) || n > .Machine$integer.max) {
    stop("the number of threads must be a positive integer")
  }
  as.integer(n)
}

