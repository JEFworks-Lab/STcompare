# The RNG kinds and .Random.seed (NULL when there is none). RNGkind() as a query does not create
# .Random.seed.
.stc_rng_save <- function() {
  list(kind = RNGkind(), seed = get0(".Random.seed", envir = globalenv(), inherits = FALSE))
}

# Put back a state from .stc_rng_save(): first the kinds (RNGkind() re-seeds the generator and writes
# .Random.seed), then .Random.seed itself, or no .Random.seed if there was none. sample.kind =
# "Rounding" warns when it is set; that warning is not repeated here.
.stc_rng_restore <- function(state) {
  suppressWarnings(RNGkind(state$kind[1], state$kind[2], state$kind[3]))
  if (is.null(state$seed)) {
    if (exists(".Random.seed", envir = globalenv(), inherits = FALSE)) {
      rm(".Random.seed", envir = globalenv())
    }
  } else {
    assign(".Random.seed", state$seed, envir = globalenv())
  }
  invisible(NULL)
}

# Save the RNG state now and put it back when the calling function exits, however it exits.
.stc_local_rng <- function(envir = parent.frame()) {
  state <- .stc_rng_save()
  do.call(base::on.exit, list(as.call(list(.stc_rng_restore, state)), add = TRUE), envir = envir)
  invisible(state)
}

# ---------------------------------------------------------------------------------------------------
# The random draws (dev/engine-spec.md 2.1 and 2.6)
# ---------------------------------------------------------------------------------------------------
#
# The streams are those of the original R implementation, so that the published results reproduce:
#   - permutations: set.seed(seed) under the RNG kinds of the calling session, the variogram subsample
#     sample(N, 1000) when N > 1000, then sample.int(N, N) for permutation b = 1, 2, ... (drawn in R);
#   - noise: permutation b uses set.seed(seed + b) under L'Ecuyer-CMRG with Inversion normals, then one
#     rnorm(N) per position of the delta grid (drawn in C++, src/stc_rng.h). The original code drew
#     these inside BiocParallel tasks, whose RNG kinds are always L'Ecuyer-CMRG and Inversion
#     (BiocParallel 1.44), whatever the session's normal.kind; the engine keeps that definition.

# The permutation stream for N pixels: set.seed(seed) under the RNG kinds in
# use now; ids <- sample(N, 1000) if N > 1000 (else 1:N); then permutation b is sample.int(N, N) (what
# sample(X) draws) for b = 1, 2, .... An environment that keeps the stream's own .Random.seed between
# batches (.stc_stream_perms()); the caller's RNG state is restored after every use.
.stc_legacy_stream <- function(N, seed) {
  .stc_local_rng()
  set.seed(seed)
  ids <- if (N > 1000) sample(N, 1000) else seq_len(N)
  s <- new.env(parent = emptyenv())
  s$N <- as.integer(N)
  s$seed <- seed
  s$ids <- ids
  s$kind <- RNGkind()
  s$start <- get(".Random.seed", envir = globalenv(), inherits = FALSE)  # permutation 1 comes next
  s$state <- s$start
  s$next_b <- 1L
  s
}

# Permutation indices b_from..b_to of a stream: an N x (b_to - b_from + 1) integer matrix. Batches are
# drawn in order; an earlier start replays the stream from permutation 1 (prefix property).
.stc_stream_perms <- function(s, b_from, b_to) {
  .stc_local_rng()
  b_from <- as.integer(b_from)
  b_to <- as.integer(b_to)
  N <- s$N
  state <- s$state
  next_b <- s$next_b
  if (b_from < next_b) {
    state <- s$start
    next_b <- 1L
  }
  assign(".Random.seed", state, envir = globalenv())
  while (next_b < b_from) {
    sample.int(N, N)
    next_b <- next_b + 1L
  }
  P <- matrix(0L, N, b_to - b_from + 1L)
  for (j in seq_len(ncol(P))) P[, j] <- sample.int(N, N)
  s$state <- get(".Random.seed", envir = globalenv(), inherits = FALSE)
  s$next_b <- b_to + 1L
  P
}

# The variogram subsample of a run with independent streams (compareSpatial()): sample(N, 1000) after
# set.seed(seed) under R's default RNG kinds (Mersenne-Twister, Inversion, Rejection) when N > 1000, else
# 1:N. This is the legacy plan's subsample under the default kinds; fixing the kinds makes it depend on the
# seed only. The caller's RNG state is restored.
.stc_subsample <- function(N, seed) {
  if (N <= 1000) return(seq_len(N))
  .stc_local_rng()
  RNGkind("Mersenne-Twister", "Inversion", "Rejection")
  set.seed(seed)
  sample(N, 1000)
}

# The noise of permutations b_from..b_to drawn with R's own rnorm() instead of the C++ generator (noise =
# "R" in .stc_engine_correlate(); slow, for tests of the C++ stream): set.seed(seed + b) under
# L'Ecuyer-CMRG with Inversion normals, then K draws of rnorm(N), one per position of a delta grid.
# Returns an N x K x (b_to - b_from + 1) array.
.stc_stream_noise <- function(s, b_from, b_to, K) {
  .stc_local_rng()
  RNGkind("L'Ecuyer-CMRG", "Inversion")
  N <- s$N
  nb <- as.integer(b_to - b_from + 1L)
  out <- array(0, c(N, K, nb))
  for (p in seq_len(nb)) {
    set.seed(s$seed + (b_from + p - 1L))
    for (k in seq_len(K)) out[, k, p] <- stats::rnorm(N)
  }
  out
}

