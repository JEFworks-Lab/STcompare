.stc_positive_int <- function(x, name) {
  v <- suppressWarnings(as.integer(x))
  if (length(x) != 1L || is.na(v) || v < 1L || v != x) stop(sprintf("%s must be a positive integer", name))
  v
}

# The streams call set.seed(seed) and set.seed(seed + b) for b = 1..B; both must be valid integers.
.stc_check_seed <- function(seed, n_max) {
  if (!is.numeric(seed) || length(seed) != 1L || !is.finite(seed) ||
      anyNA(suppressWarnings(as.integer(c(seed, seed + 1, seed + n_max))))) {
    stop("seed must be a single number such that seed and seed + nPermutations are valid integers")
  }
  invisible(TRUE)
}

# A data matrix with pixels in rows and genes in columns (a vector is one gene).
.stc_gene_matrix <- function(X, name) {
  if (is.null(X)) stop(sprintf("%s is missing", name))
  if (is.null(dim(X))) X <- matrix(X, ncol = 1L)
  X <- as.matrix(X)
  if (!is.numeric(X) && !is.logical(X)) stop(sprintf("%s must be numeric", name))
  storage.mode(X) <- "double"
  X
}

# One delta grid per gene: NULL is the default seq(0.1, 0.9, 0.1) (as in spatialCorrelation()), a vector
# is used for every gene, and a list gives one grid per gene (a NULL element takes the default).
.stc_delta_grids <- function(delta, G, name) {
  default <- seq(0.1, 0.9, 0.1)
  if (is.null(delta)) delta <- default
  if (!is.list(delta)) delta <- rep(list(delta), G)
  if (length(delta) != G) {
    stop(sprintf("%s must be a numeric vector or a list with one element per gene", name))
  }
  lapply(delta, function(d) {
    if (is.null(d)) d <- default
    if (!(is.numeric(d) || (is.logical(d) && all(is.na(d)))) || !length(d)) {
      stop(sprintf("every element of %s must be a non-empty numeric vector", name))
    }
    as.double(d)
  })
}

# Largest batch (permutations) for a memory budget on the batch's noise and permutation indices
# (option STcompare.engine_batch_bytes, default 256 MiB). With independent streams a batch needs no such
# buffers; its size then only sets how often units are scanned (and progress reported): 1024.
.stc_max_batch <- function(state) {
  if (is.null(state$stream)) return(1024L)
  budget <- getOption("STcompare.engine_batch_bytes", 256 * 2^20)
  per <- 8 * state$N * max(1L, state$kmax) * (if (state$noise_R) 2 else 1) + 4 * state$N
  max(1L, as.integer(min(.Machine$integer.max, floor(budget / per))))
}

# Null correlations, delta* and permutation p-values of many genes with the compiled engine (the
# Viladomat null of viladomatCorrelation() in both directions for every gene, with one seed).
#
# X, Y      pixels x genes matrices (the shared pixels of the two samples; a vector is one gene).
# pos       pixels x 2 coordinates (lat = pos[, 1], long = pos[, 2], the names the method uses).
# deltaX, deltaY  delta grids: NULL (default grid), one vector for every gene, or a list per gene.
# nPermutations   permutations per gene (fixed B), or, with adaptive = list(h, n_max, first_batch = 64,
#           growth = 2), Besag-Clifford stopping: each gene runs until a direction has h exceedances
#           (|null| >= |r|) or n_max permutations, in batches of first_batch, first_batch * growth, ...
#           (the batches do not change any result).
# mode      "pair": gene g of X against gene g of Y, both directions (spatialCorrelationGeneExp());
#           "forward": only the direction that permutes X (viladomatCorrelation()); a gene does not fail
#           when its Y is NA or constant: its nulls are then NA (as cor() gives them) and pX is NA;
#           "within": X only, every pair of genes (spatialCorrelationGeneExpWithinSample(); deltaX is the
#           per-gene grid, Y and deltaY are not used); one task per gene whose surrogates are correlated
#           with every other gene. Fixed B only in "forward" and "within".
# state, units    continue an earlier call (its attr(, "state")) for some units (gene indices or names;
#           all if NULL): nPermutations (or adaptive$n_max) extends them by the permutations they lack,
#           which equals a single longer run (prefix property). X, Y, pos, deltas, seed and
#           maxDistPrctile then come from the state.
# chunk     permutations per work item; batch  the largest batch (default: a memory budget, see
#           .stc_max_batch()); noise  "cpp" (default) or "R" (the same normals from R's rnorm(), for
#           tests). None of them changes any result.
# streams   "legacy" (default): the shared draws of the original implementation; "independent" (mode
#           "pair" only): every gene and direction draws its permutations and noise from its own stream,
#           keyed by (seed, gene name, direction, permutation) (src/stc_rng.h; compareSpatial()). The gene
#           names (colnames(X)) must then be unique.
#
# Returns a data.frame with one row per gene ("pair", "forward") or per pair of genes ("within", in
# combn() order): gene (or first, second), r (cor(X, Y) of each gene, as the method computes it), L
# (permutations kept), stop ("cap": n_max or B reached, "exceedances": a direction reached h, "failed"),
# bX, bY (exceedances of each direction in 1..L), pX, pY ((b + 1) / (L + 1), the p-values of fixed-B
# runs), p (the combined Besag-Clifford p-value: max(bX, bY) / L if stopped by exceedances, else
# (max(bX, bY) + 1) / (L + 1)), deltaStarMedianX, deltaStarMedianY (the median delta* of each
# direction), status ("ok" or "failed"), message, and list columns nullX, nullY, deltaStarX, deltaStarY
# (delta values) and, with returnPermutations, permutationsX and permutationsY (N x L). Failed rows have
# NA in every permutation column (an NA row); "forward" rows have NA in the Y columns. attr(, "state")
# holds the session for continuation. The caller's global RNG state is left as it was.
.stc_engine_correlate <- function(X = NULL, Y = NULL, pos = NULL, deltaX = NULL, deltaY = NULL,
                                  nPermutations = 100L, adaptive = NULL, seed = 0,
                                  maxDistPrctile = 0.25, nThreads = 1L, returnPermutations = FALSE,
                                  mode = c("pair", "forward", "within"), state = NULL, units = NULL,
                                  chunk = 16L, batch = NULL, noise = c("cpp", "R"),
                                  streams = c("legacy", "independent")) {
  .stc_local_rng()
  if (is.null(state)) {
    state <- .stc_engine_prepare(X, Y, pos, deltaX, deltaY, seed, maxDistPrctile, nThreads,
                                 returnPermutations, match.arg(mode), chunk, match.arg(noise),
                                 match.arg(streams))
  } else {
    if (!is.environment(state) || is.null(state$session)) stop("state must be attr(, \"state\") of an earlier result")
    if (!missing(nThreads) || !missing(chunk)) {
      .stc_engine_set_threads(state$session, .stc_threads(nThreads), .stc_positive_int(chunk, "chunk"))
    }
  }
  sel <- .stc_engine_select(state, units)
  .stc_engine_extend(state, sel, nPermutations, adaptive, batch)
  out <- .stc_engine_collect(state, sel)
  attr(out, "state") <- state
  out
}

# Session, tasks and units of a new engine run (see .stc_engine_correlate()). keepNulls = FALSE (only with
# independent streams, for compareSpatial()) keeps the nulls and delta* of the current batch only: the
# results are then the exceedance counts and the delta* counts per grid position (.stc_engine_task_results()
# $dstar_count), which is what the adaptive stopping and the summaries need.
.stc_engine_prepare <- function(X, Y, pos, deltaX, deltaY, seed, maxDistPrctile, nThreads,
                                returnPermutations, mode, chunk, noise, streams = "legacy",
                                keepNulls = TRUE) {
  independent <- identical(streams, "independent")
  if (independent && mode != "pair") stop("independent streams are only available for gene-wise comparisons")
  if (!independent && !keepNulls) stop("keepNulls = FALSE needs independent streams")
  X <- .stc_gene_matrix(X, "X")
  N <- nrow(X)
  G <- ncol(X)
  if (mode %in% c("pair", "forward")) {
    Y <- .stc_gene_matrix(Y, "Y")
    if (!identical(dim(Y), dim(X))) stop("X and Y must have the same dimensions (pixels x genes)")
  } else if (G < 2L) {
    stop("the within-sample mode needs at least 2 genes")
  }
  if (N < 2L) stop("at least 2 pixels are needed")
  if (G < 1L) stop("no genes")
  if (is.null(pos)) stop("pos is missing")
  pos <- as.matrix(pos)
  if (nrow(pos) != N || ncol(pos) < 2L) stop("pos must have one row per pixel and 2 columns")
  lat <- suppressWarnings(as.double(pos[, 1]))
  long <- suppressWarnings(as.double(pos[, 2]))
  if (!all(is.finite(lat)) || !all(is.finite(long))) stop("the coordinates must be finite")
  nThreads <- .stc_threads(nThreads)
  chunk <- .stc_positive_int(chunk, "chunk")
  if (independent) {
    if (!is.numeric(seed) || length(seed) != 1L || is.na(suppressWarnings(as.integer(seed))) || seed != round(seed)) {
      stop("seed must be a single integer")
    }
  } else {
    .stc_check_seed(seed, 1)
  }
  if (!is.numeric(maxDistPrctile) || length(maxDistPrctile) != 1L) stop("maxDistPrctile must be a single number")
  gridX <- .stc_delta_grids(deltaX, G, "deltaX")
  gridY <- if (mode == "pair") .stc_delta_grids(deltaY, G, "deltaY") else NULL
  genes <- colnames(X)
  if (is.null(genes)) genes <- as.character(seq_len(G))
  if (independent && (anyNA(genes) || anyDuplicated(genes))) {
    stop("independent streams need unique gene names (colnames(X)): they key the streams")
  }

  # the variogram subsample and, for the legacy streams, the permutation stream (set.seed(seed) under the
  # caller's RNG kinds)
  stream <- if (independent) NULL else .stc_legacy_stream(N, seed)
  ids <- if (independent) .stc_subsample(N, seed) else stream$ids
  # max.dist and the geoR pair table as the method computes them; where that fails (an invalid
  # maxDistPrctile, no pair below max.dist, ...) every gene gets an NA row, as in the R implementation
  plan <- tryCatch({
    prctile <- stats::quantile(stats::dist(cbind(lat[ids], long[ids])), probs = maxDistPrctile)
    .stc_variog_plan(long[ids], lat[ids], prctile)
  }, error = function(e) list(ok = FALSE, reason = conditionMessage(e)))

  noise_R <- identical(noise, "R")
  deltas <- unique(unlist(c(gridX, gridY), use.names = FALSE))
  session <- .stc_engine_new(long, lat, as.integer(ids) - 1L, plan, deltas, as.integer(.stc_cor_mode()),
                             as.double(seed), noise_R, nThreads, chunk, isTRUE(returnPermutations),
                             rng = if (independent) 1L else 0L, keep_nulls = isTRUE(keepNulls))
  grid_index <- function(g) match(g, deltas) - 1L

  if (mode == "pair") {
    pool <- cbind(X, Y)
    # the observed r of each direction, as viladomatCorrelation() computes it: cor(X, Y) and cor(Y, X)
    rX <- suppressWarnings(vapply(seq_len(G), function(g) stats::cor(X[, g], Y[, g]), 0))
    rY <- suppressWarnings(vapply(seq_len(G), function(g) stats::cor(Y[, g], X[, g]), 0))
    task_source <- as.vector(rbind(seq_len(G), G + seq_len(G))) - 1L     # X_1, Y_1, X_2, Y_2, ...
    task_targets <- as.list(as.vector(rbind(G + seq_len(G), seq_len(G))) - 1L)
    task_grid <- lapply(as.vector(rbind(gridX, gridY), "list"), grid_index)
    task_rabs <- as.list(abs(as.vector(rbind(rX, rY))))
    task_unit <- rep(seq_len(G), each = 2L) - 1L
    fail_on_dir <- rep(TRUE, G)
    r <- list(X = rX, Y = rY)
  } else if (mode == "forward") {
    pool <- cbind(X, Y)
    rX <- suppressWarnings(vapply(seq_len(G), function(g) stats::cor(X[, g], Y[, g]), 0))
    task_source <- seq_len(G) - 1L
    task_targets <- as.list(G + seq_len(G) - 1L)
    task_grid <- lapply(gridX, grid_index)
    task_rabs <- as.list(abs(rX))  # NA when r is NA: then no null counts as an exceedance
    task_unit <- seq_len(G) - 1L
    fail_on_dir <- rep(FALSE, G)  # an NA or constant Y gives NA nulls, not a failure
    r <- list(X = rX)
  } else {
    pool <- X
    # rm[i, j] = cor(X_i, X_j): pair (i, j) of spatialCorrelation() uses cor(X_i, X_j) when permuting i.
    # cor(X, X) with y given computes every element with the arithmetic of cor(X[, i], X[, j]) (R's
    # cov.c, use = "everything": each pair of columns on its own, as for two vectors), so it equals the
    # pairwise calls bit for bit, in one call instead of G^2.
    rm <- unname(suppressWarnings(stats::cor(X, X)))
    task_source <- seq_len(G) - 1L
    task_targets <- lapply(seq_len(G), function(i) setdiff(seq_len(G), i) - 1L)
    task_grid <- lapply(gridX, grid_index)
    task_rabs <- lapply(seq_len(G), function(i) abs(rm[i, -i]))
    task_unit <- seq_len(G) - 1L
    fail_on_dir <- rep(FALSE, G)
    r <- rm
  }
  # stream keys (independent streams): task 2g - 1 permutes X_g (direction 1), task 2g permutes Y_g (2)
  info <- .stc_engine_define(session, pool, as.integer(task_source), task_grid,
                             lapply(task_targets, as.integer), lapply(task_rabs, as.double),
                             as.integer(task_unit), fail_on_dir,
                             task_names = if (independent) rep(enc2utf8(genes), each = 2L),
                             task_dirs = if (independent) rep(c(1L, 2L), G))
  state <- new.env(parent = emptyenv())
  state$session <- session
  state$stream <- stream
  state$streams <- streams
  state$ids <- ids
  state$mode <- mode
  state$N <- N
  state$G <- G
  state$genes <- genes
  state$gridX <- gridX
  state$gridY <- gridY
  state$r <- r
  state$seed <- seed
  state$noise_R <- noise_R
  state$kmax <- info$kmax
  state$keep <- isTRUE(returnPermutations)
  state$plan <- plan
  state$deltas <- deltas
  state
}

# Units (genes) selected by index or name; all when NULL.
.stc_engine_select <- function(state, units) {
  if (is.null(units)) return(seq_len(state$G))
  sel <- if (is.character(units)) match(units, state$genes) else suppressWarnings(as.integer(units))
  if (!length(sel) || anyNA(sel) || any(sel < 1L | sel > state$G) || anyDuplicated(sel)) {
    stop("units must be distinct gene indices or names of the session")
  }
  sel
}

# Run batches until every selected unit has n_max permutations (fixed B: n_max = nPermutations, h = Inf),
# has stopped by exceedances, or has failed. Units with fewer permutations go first, so units at
# different lengths (a continuation) are brought to the same length before they share batches.
# progress: NULL, or a reporter (see .stc_progress() in R/compareSpatial.R) whose $batch(u, group, b_from,
# b_to) is called before every batch (u: .stc_engine_units()), $tick(done) by the engine while a batch runs,
# and $finish(u) at the end.
.stc_engine_extend <- function(state, units, nPermutations = NULL, adaptive = NULL, batch = NULL,
                               progress = NULL) {
  if (is.null(adaptive)) {
    n_max <- .stc_positive_int(nPermutations, "nPermutations")
    h <- Inf
    first <- NULL
    growth <- 1
  } else {
    if (state$mode != "pair") stop("adaptive stopping is only available for gene-wise comparisons (mode = \"pair\")")
    if (!is.list(adaptive)) stop("adaptive must be a list(h, n_max, first_batch, growth)")
    h <- as.double(adaptive$h)
    if (length(h) != 1L || is.na(h) || h < 1) stop("adaptive$h must be at least 1 (Inf: no stopping)")
    n_max <- .stc_positive_int(adaptive$n_max, "adaptive$n_max")
    first <- if (is.null(adaptive$first_batch)) 64L else .stc_positive_int(adaptive$first_batch, "adaptive$first_batch")
    growth <- if (is.null(adaptive$growth)) 2 else as.double(adaptive$growth)
    if (length(growth) != 1L || !is.finite(growth) || growth < 1) stop("adaptive$growth must be at least 1")
  }
  # the legacy noise of permutation b is set.seed(seed + b): seed + n_max must be a valid integer
  if (!is.null(state$stream)) .stc_check_seed(state$seed, n_max)
  max_batch <- if (is.null(batch)) .stc_max_batch(state) else .stc_positive_int(batch, "batch")
  step <- 0
  repeat {
    u <- .stc_engine_units(state$session)
    len <- u$len[units]
    runnable <- u$state[units] != 3L & len < n_max &
      vapply(u$counts[units], function(cn) all(cn < h), NA)
    if (!any(runnable)) break
    len0 <- min(len[runnable])
    group <- units[runnable & len == len0]
    b_from <- len0 + 1L
    size <- if (is.null(first)) max_batch else min(max_batch, max(1, floor(first * growth^step)))
    b_to <- as.integer(min(n_max, b_from + size - 1))
    # independent streams: the workers draw their own permutations and noise
    perm <- if (is.null(state$stream)) NULL else .stc_stream_perms(state$stream, b_from, b_to)
    noise <- if (state$noise_R) .stc_stream_noise(state$stream, b_from, b_to, state$kmax) else NULL
    if (!is.null(progress)) progress$batch(u, group, b_from, b_to)
    .stc_engine_run(state$session, group - 1L, b_from, b_to, perm, noise, h, n_max,
                    if (is.null(progress)) NULL else progress$tick)
    step <- step + 1
  }
  if (!is.null(progress)) progress$finish(u)
  invisible(state)
}

.stc_stop_reason <- function(st) c("active", "exceedances", "cap", "failed")[st + 1L]

# p-values of a direction and of a unit from exceedance counts at L (see .stc_engine_correlate()).
.stc_p_direction <- function(b, L) (b + 1) / (L + 1)
.stc_p_combined <- function(bmax, L, stopped_h) ifelse(stopped_h, bmax / L, (bmax + 1) / (L + 1))

.stc_engine_collect <- function(state, units) {
  u <- .stc_engine_units(state$session)
  switch(state$mode, pair = .stc_collect_pair(state, units, u), forward = .stc_collect_forward(state, units, u),
         within = .stc_collect_within(state, units, u))
}

.stc_collect_pair <- function(state, units, u) {
  n <- length(units)
  tr <- .stc_engine_task_results(state$session, as.integer(as.vector(rbind(2L * units - 2L, 2L * units - 1L))),
                                 state$keep)
  st <- u$state[units]
  ok <- st != 3L
  nullX <- nullY <- dsX <- dsY <- permX <- permY <- rep(list(NA), n)
  L <- bX <- bY <- rep(NA_integer_, n)
  medX <- medY <- rep(NA_real_, n)
  message <- rep("", n)
  for (q in seq_len(n)) {
    g <- units[q]
    if (!ok[q]) {
      ft <- u$fail_task[g]
      dir <- if (!is.na(ft) && ft %% 2L == 1L) "permuting Y" else "permuting X"
      message[q] <- paste0(dir, ": ", u$message[g])
      next
    }
    tX <- tr[[2L * q - 1L]]
    tY <- tr[[2L * q]]
    L[q] <- u$len[g]
    nullX[[q]] <- tX$nulls[, 1L]
    nullY[[q]] <- tY$nulls[, 1L]
    dsX[[q]] <- state$gridX[[g]][tX$dstar]
    dsY[[q]] <- state$gridY[[g]][tY$dstar]
    medX[q] <- stats::median(dsX[[q]])
    medY[q] <- stats::median(dsY[[q]])
    bX[q] <- u$counts[[g]][1L]
    bY[q] <- u$counts[[g]][2L]
    if (state$keep) {
      permX[[q]] <- tX$surrogates
      permY[[q]] <- tY$surrogates
    }
  }
  res <- data.frame(gene = state$genes[units], r = state$r$X[units], L = L,
                    stop = .stc_stop_reason(st), bX = bX, bY = bY,
                    pX = .stc_p_direction(bX, L), pY = .stc_p_direction(bY, L),
                    p = .stc_p_combined(pmax(bX, bY), L, st == 1L),
                    deltaStarMedianX = medX, deltaStarMedianY = medY,
                    status = ifelse(ok, "ok", "failed"), message = message, stringsAsFactors = FALSE)
  res$nullX <- I(nullX)
  res$nullY <- I(nullY)
  res$deltaStarX <- I(dsX)
  res$deltaStarY <- I(dsY)
  if (state$keep) {
    res$permutationsX <- I(permX)
    res$permutationsY <- I(permY)
  }
  rownames(res) <- make.unique(state$genes[units])
  res
}

# One direction (permute X, correlate with Y). A unit fails only through X (or the plan, or a smoother);
# an NA or constant Y leaves the surrogates and delta* intact and makes the nulls NA, and an NA in the
# nulls or in r makes pX NA (sum(abs(null) >= abs(r)) is NA in R). Such rows have status "ok" and a
# message.
.stc_collect_forward <- function(state, units, u) {
  n <- length(units)
  tr <- .stc_engine_task_results(state$session, as.integer(units - 1L), state$keep)
  st <- u$state[units]
  ok <- st != 3L
  nullX <- dsX <- permX <- rep(list(NA), n)
  L <- bX <- rep(NA_integer_, n)
  medX <- rep(NA_real_, n)
  message <- rep("", n)
  for (q in seq_len(n)) {
    g <- units[q]
    if (!ok[q]) {
      message[q] <- paste0("permuting X: ", u$message[g])
      next
    }
    tX <- tr[[q]]
    L[q] <- u$len[g]
    nullX[[q]] <- tX$nulls[, 1L]
    dsX[[q]] <- state$gridX[[g]][tX$dstar]
    medX[q] <- stats::median(dsX[[q]])
    if (state$keep) permX[[q]] <- tX$surrogates
    ts <- tX$target_status[1L]
    if (ts != 0L || anyNA(nullX[[q]]) || is.na(state$r$X[g])) {
      message[q] <- if (ts == 2L) {
        "the values correlated with the permutations contain NA, NaN or Inf"
      } else if (ts == 4L) {
        "the values correlated with the permutations are constant (zero variance)"
      } else if (!is.na(tX$dir_fail_b[1L])) {
        sprintf("permutation %d: a null correlation is NA", tX$dir_fail_b[1L])
      } else {
        "the observed correlation is NA"
      }
    } else {
      bX[q] <- u$counts[[g]][1L]
    }
  }
  res <- data.frame(gene = state$genes[units], r = state$r$X[units], L = L,
                    stop = .stc_stop_reason(st), bX = bX, bY = NA_integer_,
                    pX = .stc_p_direction(bX, L), pY = NA_real_, p = .stc_p_direction(bX, L),
                    deltaStarMedianX = medX, deltaStarMedianY = NA_real_,
                    status = ifelse(ok, "ok", "failed"), message = message, stringsAsFactors = FALSE)
  res$nullX <- I(nullX)
  res$nullY <- I(rep(list(NA), n))
  res$deltaStarX <- I(dsX)
  res$deltaStarY <- I(rep(list(NA), n))
  if (state$keep) {
    res$permutationsX <- I(permX)
    res$permutationsY <- I(rep(list(NA), n))
  }
  rownames(res) <- make.unique(state$genes[units])
  res
}

# Pair (i, j), i < j, takes the X columns from gene i's task (its surrogates correlated with gene j) and
# the Y columns from gene j's task, over the first min(L_i, L_j) permutations. The pairs are filled gene
# by gene, not one at a time: the number of pairs grows with the square of the number of genes.
.stc_collect_within <- function(state, units, u) {
  units <- sort(units)
  pairs <- utils::combn(units, 2L)
  tr <- .stc_engine_task_results(state$session, as.integer(units - 1L), state$keep)
  np <- ncol(pairs)
  gi <- pairs[1L, ]
  gj <- pairs[2L, ]
  # With sorted units gi < gj, so gene gj is target gj - 1 of gene gi (a gene's targets are all other
  # genes, in order) and gene gi is target gi of gene gj.
  rX <- state$r[cbind(gi, gj)]
  rY <- state$r[cbind(gj, gi)]
  Lq <- pmin(u$len[gi], u$len[gj])
  failed <- u$state == 3L
  as_first <- split(seq_len(np), factor(gi, levels = units))   # pairs of each gene, by position in units
  as_second <- split(seq_len(np), factor(gj, levels = units))
  # first permutation whose null correlation is NA, in each direction (NA: none)
  failX <- failY <- rep(NA_integer_, np)
  for (a in seq_along(units)) {
    if (failed[units[a]]) next
    qa <- as_first[[a]]
    qb <- as_second[[a]]
    failX[qa] <- tr[[a]]$dir_fail_b[gj[qa] - 1L]
    failY[qb] <- tr[[a]]$dir_fail_b[gi[qb]]
  }
  bad_i <- failed[gi]
  bad_j <- failed[gj]
  gene_msg <- paste0(state$genes, ": ", u$message)
  message <- rep("", np)
  message[bad_i] <- gene_msg[gi[bad_i]]
  message[bad_j & !bad_i] <- gene_msg[gj[bad_j & !bad_i]]
  both <- bad_i & bad_j
  message[both] <- paste(gene_msg[gi[both]], gene_msg[gj[both]], sep = "; ")
  fx <- !bad_i & !bad_j & !is.na(failX) & failX <= Lq
  fy <- !bad_i & !bad_j & !fx & !is.na(failY) & failY <= Lq
  message[fx] <- sprintf("permuting %s, permutation %d: the null correlation with %s is NA",
                         state$genes[gi[fx]], failX[fx], state$genes[gj[fx]])
  message[fy] <- sprintf("permuting %s, permutation %d: the null correlation with %s is NA",
                         state$genes[gj[fy]], failY[fy], state$genes[gi[fy]])
  ok <- !(bad_i | bad_j | fx | fy)
  status <- ifelse(ok, "ok", "failed")
  L <- rep(NA_integer_, np)
  L[ok] <- Lq[ok]

  nullX <- nullY <- dsX <- dsY <- permX <- permY <- rep(list(NA), np)
  bX <- bY <- rep(NA_integer_, np)
  medX <- medY <- rep(NA_real_, np)
  # the columns of a matrix as a list of vectors (split() with a ready-made factor: no conversion)
  columns <- function(M) {
    nc <- ncol(M)
    f <- structure(rep(seq_len(nc), each = nrow(M)), levels = as.character(seq_len(nc)), class = "factor")
    unname(split.default(M, f))
  }
  for (a in seq_along(units)) {
    g <- units[a]
    if (failed[g]) next
    task <- tr[[a]]
    for (first in c(TRUE, FALSE)) {
      # gene g permuted: as the first gene of a pair (X columns) or as the second (Y columns)
      q <- if (first) as_first[[a]] else as_second[[a]]
      q <- q[ok[q]]
      for (len in unique(Lq[q])) {
        s <- q[Lq[q] == len]
        target <- if (first) gj[s] - 1L else gi[s]
        r_abs <- abs(if (first) rX[s] else rY[s])
        M <- task$nulls[seq_len(len), target, drop = FALSE]
        nulls <- columns(M)
        b <- as.integer(colSums(abs(M) >= rep(r_abs, each = len)))
        ds <- state$gridX[[g]][task$dstar[seq_len(len)]]  # one vector (and median) shared by the pairs
        med <- stats::median(ds)
        if (first) {
          nullX[s] <- nulls
          bX[s] <- b
          dsX[s] <- list(ds)
          medX[s] <- med
          if (state$keep) permX[s] <- list(task$surrogates)
        } else {
          nullY[s] <- nulls
          bY[s] <- b
          dsY[s] <- list(ds)
          medY[s] <- med
          if (state$keep) permY[s] <- list(task$surrogates)
        }
      }
    }
  }
  st <- ifelse(ok, 2L, 3L)
  res <- data.frame(first = state$genes[pairs[1L, ]], second = state$genes[pairs[2L, ]], r = rX, L = L,
                    stop = .stc_stop_reason(st), bX = bX, bY = bY,
                    pX = .stc_p_direction(bX, L), pY = .stc_p_direction(bY, L),
                    p = .stc_p_combined(pmax(bX, bY), L, FALSE),
                    deltaStarMedianX = medX, deltaStarMedianY = medY,
                    status = status, message = message, stringsAsFactors = FALSE)
  res$nullX <- I(nullX)
  res$nullY <- I(nullY)
  res$deltaStarX <- I(dsX)
  res$deltaStarY <- I(dsY)
  if (state$keep) {
    res$permutationsX <- I(permX)
    res$permutationsY <- I(permY)
  }
  res
}

