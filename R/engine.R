# A numeric vector from a vector or a one-row or one-column matrix.
.stc_values <- function(x, name) {
  if (is.null(x)) stop(sprintf("%s is missing", name))
  if (!is.null(dim(x))) {
    if (length(dim(x)) != 2L || min(dim(x)) != 1L) {
      stop(sprintf("%s must be a numeric vector (or a matrix with one row or one column)", name))
    }
    x <- as.matrix(x)
    x <- as.vector(if (nrow(x) == 1L) x[1L, ] else x[, 1L])
  }
  if (is.factor(x) || !(is.numeric(x) || is.logical(x))) stop(sprintf("%s must be numeric", name))
  as.double(x)
}

# nPermutations of the fixed-B functions.
.stc_check_nperm <- function(nPermutations) {
  if (!is.numeric(nPermutations) || length(nPermutations) != 1L || is.na(nPermutations) ||
      nPermutations < 1 || nPermutations != round(nPermutations) || nPermutations > .Machine$integer.max) {
    stop("nPermutations must be a positive integer")
  }
  as.integer(nPermutations)
}

# One delta grid per gene from a list (or vector) with one element per gene, as the gene-wise functions
# index it (delta[[i]] for gene i); NULL gives every gene the default grid.
.stc_gene_deltas <- function(delta, G, name) {
  if (is.null(delta)) return(rep(list(NULL), G))
  if (length(delta) != G) {
    stop(sprintf("%s must be a list with one element (a numeric vector of deltas) per gene: %d genes, %d elements",
                 name, G, length(delta)))
  }
  lapply(seq_len(G), function(i) delta[[i]])
}

# The two SpatialExperiment objects of a gene-wise comparison: shared pixels (in the order of the first
# object), their coordinates, and pixels x genes matrices of the assay (genes of the first object, taken
# by name from both).
.stc_pair_input <- function(input, assayName) {
  if (length(input) < 2L) stop("input must be a list of two SpatialExperiment objects")
  source <- input[[1]]
  target <- input[[2]]
  if (is.null(assayName)) assayName <- 1
  genes <- rownames(source)
  if (is.null(genes) || !length(genes)) stop("the first SpatialExperiment object has no row names (genes)")
  shared <- intersect(rownames(SpatialExperiment::spatialCoords(source)),
                      rownames(SpatialExperiment::spatialCoords(target)))
  if (length(shared) < 3L) {
    stop(sprintf("the two SpatialExperiment objects share %d pixel(s); at least 3 are needed", length(shared)))
  }
  pos <- SpatialExperiment::spatialCoords(source)[shared, , drop = FALSE]
  a <- SummarizedExperiment::assay(source, assayName)
  b <- SummarizedExperiment::assay(target, assayName)
  missing_genes <- setdiff(genes, rownames(b))
  if (length(missing_genes)) {
    stop(sprintf("%d gene(s) of the first object are missing from the second, for example %s",
                 length(missing_genes), missing_genes[1]))
  }
  X <- t(as.matrix(a[genes, shared, drop = FALSE]))
  Y <- t(as.matrix(b[genes, shared, drop = FALSE]))
  storage.mode(X) <- "double"
  storage.mode(Y) <- "double"
  colnames(X) <- colnames(Y) <- genes
  list(genes = genes, pos = pos, X = X, Y = Y)
}

# cor.test(x, y) for the column pairs (X[, ix[k]], Y[, iy[k]]): the estimate and the naive p-value, as
# cor.test() computes them. When both columns are finite and there are at least 3 pixels, cor.test() uses
# every pixel: its estimate is r = cor(x, y) and its p-value is 2 * min(pt(t, df), pt(t, df, lower.tail =
# FALSE)) with df = N - 2 and t = sqrt(df) * r / sqrt(1 - r^2). Those pairs are computed here all at once
# with exactly that arithmetic; r_pairs, if given, is cor(X[, ix[k]], Y[, iy[k]]) of every pair as R's
# cor() computed it elsewhere (otherwise it is computed here). The other pairs (missing or infinite values,
# fewer than 3 pixels) go through cor.test() itself. Warnings (a zero standard deviation) are muffled,
# because such a gene also gets an NA row whose warning names it; where cor.test() fails (fewer than 3
# complete pairs), r and p are NA and the error is kept in msg.
.stc_cor_tests <- function(X, Y, ix = seq_len(ncol(X)), iy = ix, r_pairs = NULL) {
  n <- length(ix)
  N <- nrow(X)
  r <- p <- rep(NA_real_, n)
  msg <- rep("", n)
  finite <- function(M) vapply(seq_len(ncol(M)), function(j) all(is.finite(M[, j])), NA)
  fx <- finite(X)
  fy <- if (identical(X, Y)) fx else finite(Y)
  fast <- N >= 3L & fx[ix] & fy[iy]
  if (any(fast)) {
    r[fast] <- if (is.null(r_pairs)) {
      suppressWarnings(vapply(which(fast), function(k) stats::cor(X[, ix[k]], Y[, iy[k]]), 0))
    } else {
      r_pairs[fast]
    }
    df <- N - 2L
    tstat <- sqrt(df) * r[fast] / sqrt(1 - r[fast]^2)
    p[fast] <- 2 * pmin(stats::pt(tstat, df), stats::pt(tstat, df, lower.tail = FALSE))
  }
  for (i in which(!fast)) {
    ct <- tryCatch(suppressWarnings(stats::cor.test(X[, ix[i]], Y[, iy[i]])), error = function(e) e)
    if (inherits(ct, "error")) {
      msg[i] <- paste("cor.test() failed:", conditionMessage(ct))
    } else {
      r[i] <- unname(ct$estimate)
      p[i] <- ct$p.value
    }
  }
  list(r = r, p = p, msg = msg)
}

# The table of the gene-wise functions from cor.test() results and an engine result ("pair" or
# "within" rows): numeric columns correlationCoef, pValueNaive, pValuePermuteX/Y, deltaStarMedianX/Y,
# and AsIs list columns deltaStarX/Y (delta* of every permutation), nullCorrelationsX/Y (B x 1
# matrices) and, with keep, permutationsX/Y (N x B matrices). An NA row has NA in every column computed
# from permutations (NA elements in the list columns).
.stc_result_table <- function(naive, e, keep, row_names) {
  n <- nrow(e)
  ok <- e$status == "ok"
  pick <- function(v) {
    v <- unclass(v)
    v[!ok] <- list(NA)
    v
  }
  # B x 1 matrices (dim<- gives what matrix(x, ncol = 1L) gives, without its argument checks)
  as_col <- function(v) {
    out <- rep(list(NA), n)
    out[ok] <- lapply(unclass(v)[ok], function(x) {
      dim(x) <- c(length(x), 1L)
      x
    })
    out
  }
  out <- data.frame(correlationCoef = as.double(naive$r), pValueNaive = as.double(naive$p),
                    pValuePermuteX = ifelse(ok, as.double(e$pX), NA_real_),
                    pValuePermuteY = ifelse(ok, as.double(e$pY), NA_real_),
                    deltaStarMedianX = ifelse(ok, as.double(e$deltaStarMedianX), NA_real_),
                    deltaStarMedianY = ifelse(ok, as.double(e$deltaStarMedianY), NA_real_))
  out$deltaStarX <- I(pick(e$deltaStarX))
  out$deltaStarY <- I(pick(e$deltaStarY))
  out$nullCorrelationsX <- I(as_col(e$nullX))
  out$nullCorrelationsY <- I(as_col(e$nullY))
  if (keep) {
    out$permutationsX <- I(pick(e$permutationsX))
    out$permutationsY <- I(pick(e$permutationsY))
  }
  rownames(out) <- row_names
  out
}

# One warning() per NA row (never print()): fun, the row's label (NULL for a single comparison), and why.
.stc_warn_na_rows <- function(fun, labels, e, naive = NULL) {
  bad <- which(e$status != "ok")
  for (i in bad) {
    why <- e$message[i]
    if (!is.null(naive) && nzchar(naive$msg[i])) why <- paste0(naive$msg[i], "; ", why)
    warning(sprintf("%s: %sno permutation p-values (NA row): %s", fun,
                    if (is.null(labels)) "" else paste0(labels[i], ": "), why), call. = FALSE)
  }
  invisible(length(bad))
}

# Elapsed seconds since t0 (proc.time()), for the verbose end messages.
.stc_elapsed <- function(t0) sprintf("%.1f s", (proc.time() - t0)[["elapsed"]])
